# Load environment variables from a .env file if present.
# We try to use python-dotenv when available; if not, fall back to a
# very small parser so settings still work without extra packages.
env_path = BASE_DIR / '.env'
if env_path.exists():
    try:
        # preferred: python-dotenv
        from dotenv import load_dotenv

        load_dotenv(dotenv_path=env_path)
    except Exception:
        # fallback: parse KEY=VALUE lines (simple, ignores quotes)
        for raw in env_path.read_text(encoding='utf-8').splitlines():
            line = raw.strip()
            if not line or line.startswith('#'):
                continue
            if '=' not in line:
                continue
            k, v = line.split('=', 1)
            k = k.strip()
            v = v.strip().strip("'\"")
            os.environ.setdefault(k, v)


